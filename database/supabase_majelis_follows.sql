-- Tabel majelis_follows untuk masjid/majelis yang diikuti (persisten)
CREATE TABLE IF NOT EXISTS public.majelis_follows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  masjid TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(user_id, masjid)
);

CREATE INDEX IF NOT EXISTS idx_majelis_follows_user ON public.majelis_follows(user_id);
CREATE INDEX IF NOT EXISTS idx_majelis_follows_masjid ON public.majelis_follows(masjid);

ALTER TABLE public.majelis_follows ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "service_role_all" ON public.majelis_follows;
CREATE POLICY "service_role_all" ON public.majelis_follows
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "anon_select" ON public.majelis_follows;
CREATE POLICY "anon_select" ON public.majelis_follows
  FOR SELECT
  TO anon
  USING (true);
