-- 1. TABEL KAJIAN (Jadwal & Agenda Kajian)
CREATE TABLE IF NOT EXISTS public.kajian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    ustadz TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Kajian',
    audience TEXT NOT NULL DEFAULT 'Umum',
    masjid TEXT NOT NULL,
    address TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL DEFAULT 0,
    lon DOUBLE PRECISION NOT NULL DEFAULT 0,
    day TEXT NOT NULL DEFAULT '',
    time TEXT NOT NULL DEFAULT '',
    description TEXT,
    verified BOOLEAN NOT NULL DEFAULT true,
    source TEXT NOT NULL DEFAULT 'instagram' CHECK (source IN ('instagram', 'facebook', 'threads')),
    source_url TEXT,
    flyer_url TEXT,
    event_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.kajian ADD COLUMN IF NOT EXISTS flyer_url TEXT;
ALTER TABLE public.kajian ADD COLUMN IF NOT EXISTS event_date DATE;

CREATE INDEX IF NOT EXISTS idx_kajian_category ON public.kajian (category);
CREATE INDEX IF NOT EXISTS idx_kajian_verified ON public.kajian (verified);
CREATE INDEX IF NOT EXISTS idx_kajian_event_date ON public.kajian (event_date);
CREATE INDEX IF NOT EXISTS idx_kajian_coords ON public.kajian (lat, lon);

ALTER TABLE public.kajian ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "kajian_public_read" ON public.kajian;
CREATE POLICY "kajian_public_read" ON public.kajian
    FOR SELECT TO anon, authenticated
    USING (verified = true);

DROP POLICY IF EXISTS "kajian_service_role_all" ON public.kajian;
CREATE POLICY "kajian_service_role_all" ON public.kajian
    FOR ALL TO service_role
    USING (true) WITH CHECK (true);


-- 2. TABEL APP_USERS (Otentikasi & Akun Jamaah)
CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255),
    avatar TEXT,
    provider VARCHAR(50),
    provider_id VARCHAR(255),
    email_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.app_users ADD COLUMN IF NOT EXISTS avatar TEXT;

CREATE INDEX IF NOT EXISTS idx_app_users_email ON public.app_users (email);

ALTER TABLE public.app_users ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "app_users_service_role_all" ON public.app_users;
CREATE POLICY "app_users_service_role_all" ON public.app_users
    FOR ALL TO service_role
    USING (true) WITH CHECK (true);


-- 3. TABEL BOOKMARKS (Kajian Tersimpan per User)
CREATE TABLE IF NOT EXISTS public.bookmarks (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    kajian_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, kajian_id)
);

CREATE INDEX IF NOT EXISTS idx_bookmarks_user ON public.bookmarks (user_id);
CREATE INDEX IF NOT EXISTS idx_bookmarks_kajian ON public.bookmarks (kajian_id);

ALTER TABLE public.bookmarks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "bookmarks_service_role_all" ON public.bookmarks;
CREATE POLICY "bookmarks_service_role_all" ON public.bookmarks
    FOR ALL TO service_role
    USING (true) WITH CHECK (true);


-- 4. TABEL ATTENDANCES (Presensi Kehadiran Kajian)
CREATE TABLE IF NOT EXISTS public.attendances (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    kajian_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, kajian_id, attendance_date)
);

CREATE INDEX IF NOT EXISTS idx_attendances_user ON public.attendances (user_id);

ALTER TABLE public.attendances ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "attendances_service_role_all" ON public.attendances;
CREATE POLICY "attendances_service_role_all" ON public.attendances
    FOR ALL TO service_role
    USING (true) WITH CHECK (true);


-- 5. TABEL MAJELIS_FOLLOWS (Masjid / Majelis yang Diikuti)
CREATE TABLE IF NOT EXISTS public.majelis_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    masjid TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, masjid)
);

CREATE INDEX IF NOT EXISTS idx_majelis_follows_user ON public.majelis_follows (user_id);
CREATE INDEX IF NOT EXISTS idx_majelis_follows_masjid ON public.majelis_follows (masjid);

ALTER TABLE public.majelis_follows ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "majelis_follows_service_role_all" ON public.majelis_follows;
CREATE POLICY "majelis_follows_service_role_all" ON public.majelis_follows
    FOR ALL TO service_role
    USING (true) WITH CHECK (true);
